async def handle_message(update: Update, context: ContextTypes.DEFAULT_TYPE):
    text = update.message.text.strip().lower()

    # ရိုက်ထည့်လိုက်သော စာသားအပေါ် မူတည်ပြီး သက်ဆိုင်ရာ ရာသီခွင်ကို ရှာဖွေခြင်း
    matched_key = None
    for key in ZODIAC_DATA.keys():
        if key in text:
            matched_key = key
            break

    # သို့မဟုတ် အကယ်၍ လအမည်များ (ဥပမာ ဇန်နဝါရီ၊ ဖေဖော်ဝါရီ စသဖြင့်) ပါလာပါက သက်ဆိုင်ရာရာသီခွင်သို့ အလိုအလျောက် သတ်မှတ်ပေးခြင်း
    if not matched_key:
        if any(w in text for w in ["မတ်", "ဧပြီ", "တန်ခူး"]):
            matched_key = "မိဿ"
        elif any(w in text for w in ["ဧပြီ", "မေ", "ကဆုန်"]):
            matched_key = "ပြိဿ"
        elif any(w in text for w in ["မေ", "ဇွန်", "နယုန်"]):
            matched_key = "မေထုန်"
        elif any(w in text for w in ["ဇွန်", "ဇူလိုင်", "ဝါဆို"]):
            matched_key = "ကရကဋ်"
        elif any(w in text for w in ["ဇူလိုင်", "သဂုတ်", "ဝါခေါင်"]):
            matched_key = "သိဟ်"
        elif any(w in text for w in ["သဂုတ်", "စက်တင်ဘာ", "တော်သလင်း"]):
            matched_key = "ကန်"
        elif any(w in text for w in ["စက်တင်ဘာ", "အောက်တိုဘာ", "သီတင်းကျွတ်"]):
            matched_key = "တူ"
        elif any(w in text for w in ["အောက်တိုဘာ", "နိုဝင်ဘာ", "တန်ဆောင်မုန်း"]):
            matched_key = "ဗြိစ္ဆာ"
        elif any(w in text for w in ["နိုဝင်ဘာ", "ဒီဇင်ဘာ", "နတ်တော်"]):
            matched_key = "ဓနု"
        elif any(w in text for w in ["ဒီဇင်ဘာ", "ဇန်နဝါရီ", "ပြာသို"]):
            matched_key = "မကာရ"
        elif any(w in text for w in ["ဇန်နဝါရီ", "ဖေဖော်ဝါရီ", "တပို့တွဲ"]):
            matched_key = "ကုမ်"
        elif any(w in text for w in ["ဖေဖော်ဝါရီ", "မတ်", "တပေါင်း"]):
            matched_key = "မိန်"
        else:
            # အကယ်၍ လုံးဝမတိုက်ဆိုင်ပါက စာရင်းထဲမှ တစ်ခုခုကို ကျပန်းရွေးထုတ်ပေးမည်
            matched_key = random.choice(list(ZODIAC_DATA.keys()))

    info = ZODIAC_DATA[matched_key]
    response = (
        f"🔮 **သင်ထည့်သွင်းလိုက်သော အချက်အလက်အတွက် ဟောကိန်း**\n"
        f"━━━━━━━━━━━━━━━━━━━\n"
        f"✨ **ရာသီခွင်:** {info['name']}\n\n"
        f"🧠 **စိတ်နေစိတ်ထား:**\n• {info['traits']}\n\n"
        f"❤️ **အချစ်ရေး:**\n• {info['love']}\n\n"
        f"💼 **လုပ်ငန်းခွင်နှင့် စီးပွားရေး:**\n• {info['career']}\n\n"
        f"⚠️ **သတိပြုရှောင်ရှားစရာ:**\n• {info['caution']}"
    )

    keyboard = [
        [
            InlineKeyboardButton("🔄 အခြားတစ်ခု ထပ်မံမေးမည်", callback_data="menu_zodiac"),
            InlineKeyboardButton("🏠 ပင်မမီနူးသို့", callback_data="menu_start"),
        ]
    ]
    await update.message.reply_text(
        response, parse_mode="Markdown", reply_markup=InlineKeyboardMarkup(keyboard)
    )


